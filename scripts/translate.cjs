function extractSegments(html) {
  const segments = [];
  let remaining = html;
  while (remaining.length > 0) {
    const tagStart = remaining.indexOf('<');
    if (tagStart === -1) {
      segments.push({ type: 'text', content: remaining });
      break;
    }
    if (tagStart > 0) {
      segments.push({ type: 'text', content: remaining.substring(0, tagStart) });
    }
    const tagEnd = remaining.indexOf('>', tagStart);
    if (tagEnd === -1) {
      segments.push({ type: 'text', content: remaining.substring(tagStart) });
      break;
    }
    segments.push({ type: 'tag', content: remaining.substring(tagStart, tagEnd + 1) });
    remaining = remaining.substring(tagEnd + 1);
  }
  return segments;
}

function rebuildHtml(segments) {
  return segments.map(s => s.content).join('');
}

