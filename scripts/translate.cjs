for (const key of Object.keys(englishBodies)) {
  const body = englishBodies[key];
  const segments = extractSegments(body);
  
  if (translations[key]) {
    for (const [idxStr, arabic] of Object.entries(translations[key])) {
      const idx = parseInt(idxStr);
      if (idx < segments.length && segments[idx].type === 'text') {
        segments[idx].content = arabic;
      }
    }
  }
  
  const translatedBody = rebuildHtml(segments);
  if (saData && saData.pages && saData.pages[key]) {
    saData.pages[key].body = translatedBody;
  }
}

